#!/usr/bin/env python3
"""Build the MediaTek IMS service for LineageOS from the stock Bigme system_ext.

Stock (Android 14) ships MediaTek's ImsService (com.mediatek.ims) in
system_ext/priv-app/ImsService and loads two of its libraries, mediatek-ims-base and
mediatek-common, from the boot classpath. Nothing else of MediaTek's telephony framework is
used by it. Our system has no MediaTek jars on the boot classpath, so this
script folds the two libraries into the APK as classes2.dex and classes3.dex and drops the
stock signature; the build re-signs it with the platform key (android_app_import,
certificate "platform").

Output (the private vendor tree, not in git):
  vendor/bigme/hibreakpro/proprietary/system_ext/priv-app/ImsService/ImsService.apk
  vendor/bigme/hibreakpro/proprietary/system_ext/priv-app/ImsService/Android.bp
  vendor/bigme/hibreakpro/proprietary/system_ext/priv-app/ImsService/SOURCES.txt (input hashes)

Usage: extract-ims.py [--stock <system_ext dir>] [--vendor <vendor/bigme/hibreakpro>]
       defaults: backup/fs/system_ext and vendor/bigme/hibreakpro under the repo root.
"""
import argparse
import hashlib
import os
import struct
import sys
import zipfile

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "..", ".."))
LIBS = ["framework/mediatek-ims-base.jar", "framework/mediatek-common.jar"]
APK = "priv-app/ImsService/ImsService.apk"

ANDROID_BP = """\
// Generated by device/bigme/hibreakpro/tools/ims/extract-ims.py: do not edit.
// MediaTek's IMS service from the stock Bigme firmware, with mediatek-ims-base and
// mediatek-common folded in. Shares android.uid.phone, so platform-signed.
android_app_import {
    name: "MtkImsService",
    apk: "ImsService.apk",
    certificate: "platform",
    privileged: true,
    system_ext_specific: true,
    // The manifest lists MediaTek's operator plugins com.mediatek.ims.plugin and
    // com.mediatek.ims.oemplugin as optional <uses-library>; we ship neither, so no
    // class loader context to check or preopt against (ART compiles it on the device).
    enforce_uses_libs: false,
    dex_preopt: {
        enabled: false,
    },
}
"""


def dex_classes(b):
    type_ids_size, type_ids_off = struct.unpack_from("<II", b, 0x40)
    class_defs_size, class_defs_off = struct.unpack_from("<II", b, 0x60)
    string_ids_off = struct.unpack_from("<I", b, 0x3C)[0]

    def string(i):
        off = struct.unpack_from("<I", b, string_ids_off + 4 * i)[0]
        while b[off] & 0x80:  # skip uleb128 length
            off += 1
        off += 1
        return b[off:b.index(0, off)].decode("utf-8", "replace")

    out = set()
    for i in range(class_defs_size):
        tidx = struct.unpack_from("<I", b, class_defs_off + 32 * i)[0]
        out.add(string(struct.unpack_from("<I", b, type_ids_off + 4 * tidx)[0]))
    return out


def only_dex(path):
    with zipfile.ZipFile(path) as z:
        dexes = [n for n in z.namelist() if n.startswith("classes") and n.endswith(".dex")]
        if dexes != ["classes.dex"]:
            sys.exit(f"{path}: expected exactly classes.dex, found {dexes}")
        return z.read("classes.dex")


def write_aligned(zout, info, data):
    """Store uncompressed entries 4-byte aligned (resources.arsc must be; dex should be)."""
    if info.compress_type == zipfile.ZIP_STORED:
        offset = zout.fp.tell() + 30 + len(info.filename.encode())
        pad = (-offset) % 4
        info.extra = b"\0" * pad
    zout.writestr(info, data)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stock", default=os.path.join(REPO, "backup/fs/system_ext"))
    ap.add_argument("--vendor", default=os.path.join(REPO, "vendor/bigme/hibreakpro"))
    a = ap.parse_args()

    src_apk = os.path.join(a.stock, APK)
    outdir = os.path.join(a.vendor, "proprietary/system_ext/priv-app/ImsService")
    os.makedirs(outdir, exist_ok=True)

    extra = [only_dex(os.path.join(a.stock, lib)) for lib in LIBS]
    seen = {}
    with zipfile.ZipFile(src_apk) as zin:
        names = zin.namelist()
        if [n for n in names if n.startswith("classes") and n.endswith(".dex")] != ["classes.dex"]:
            sys.exit(f"{src_apk}: expected a single classes.dex")
        for label, dex in [("ImsService.apk", zin.read("classes.dex"))] + list(zip(LIBS, extra)):
            for c in dex_classes(dex):
                if c in seen:
                    sys.exit(f"class {c} defined in both {seen[c]} and {label}")
                seen[c] = label

        tmp = os.path.join(outdir, "ImsService.apk.tmp")
        with zipfile.ZipFile(tmp, "w") as zout:
            for info in zin.infolist():
                if info.filename.startswith("META-INF/"):
                    continue  # stock signature; the build signs with our platform key
                data = zin.read(info)
                new = zipfile.ZipInfo(info.filename, date_time=(2009, 1, 1, 0, 0, 0))
                new.compress_type = info.compress_type
                new.external_attr = info.external_attr
                write_aligned(zout, new, data)
                if info.filename == "classes.dex":
                    for n, dex in enumerate(extra, start=2):
                        d = zipfile.ZipInfo(f"classes{n}.dex", date_time=(2009, 1, 1, 0, 0, 0))
                        d.compress_type = zipfile.ZIP_STORED
                        write_aligned(zout, d, dex)
        os.replace(tmp, os.path.join(outdir, "ImsService.apk"))

    with open(os.path.join(outdir, "Android.bp"), "w") as f:
        f.write(ANDROID_BP)
    with open(os.path.join(outdir, "SOURCES.txt"), "w") as f:
        f.write("# sha256 of the stock files ImsService.apk was built from (system_ext)\n")
        for rel in [APK] + LIBS:
            h = hashlib.sha256(open(os.path.join(a.stock, rel), "rb").read()).hexdigest()
            f.write(f"{h}  {rel}\n")
    print(f"wrote {outdir}/ImsService.apk ({len(seen)} classes in 3 dex files)")


if __name__ == "__main__":
    main()
