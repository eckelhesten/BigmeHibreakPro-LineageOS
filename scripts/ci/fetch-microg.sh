#!/bin/bash
# Runs ON the build server (called by buildserver-build.sh when vendor/microg is missing):
# fetch the pinned official microG release and turn it into product-partition modules.
#
# - Downloads GmsCore (com.google.android.gms) and Companion (com.android.vending) from
#   github.com/microg/GmsCore, checks the pinned SHA-256 of each file, and refuses an APK unless
#   it is signed by microG's certificate: the one LineageOS lets fake Google's signature
#   (MICROG_REAL_SIGNATURE in frameworks/base ComputerEngine.java).
# - Writes vendor/microg/Android.bp (its own Soong namespace; privileged, presigned apps on
#   /product) and the
#   privapp-permissions allowlist. LineageOS enforces the allowlist (a missing entry stops the
#   boot), so it lists every privileged permission the APKs request, from all permission
#   definitions in the source tree.
# - Default runtime grants (location, phone state, notifications) and power-save exemption for
#   push messages, as LineageOS for microG does.
#
# To update microG: change VERSION / the file names / the SHA-256 values below (from the release
# page's asset digests), delete vendor/microg on the server and build.
set -euo pipefail
cd /srv/lineage
VERSION=v0.3.18.252432
GMS=com.google.android.gms-252432036.apk
GMS_SHA=1094fa60ace2367ac52bd08d1bd4f33fa8144ba930e355121b28234b8ebbf382
STORE=com.android.vending-84022636.apk
STORE_SHA=3f1bde2f72bca746fbb53b61a32c2a85fcb026f886ee96d6fe9a05de9a6c6d5b
MICROG_CERT_SHA256=9bd06727e62796c0130eb6dab39b73157451582cbd138e86c468acc395d14165

D=vendor/microg
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
fetch() { # file sha256 -> $tmp/file
  curl -fsSL -H "User-Agent: hibreak-build" -o "$tmp/$1" \
    "https://github.com/microg/GmsCore/releases/download/$VERSION/$1"
  echo "$2  $tmp/$1" | sha256sum -c --quiet || { echo "checksum mismatch: $1"; exit 1; }
  local cert apksigner=prebuilts/sdk/tools/linux/lib/apksigner.jar
  [ -f "$apksigner" ] || apksigner=prebuilts/sdk/tools/darwin/lib/apksigner.jar
  cert=$(prebuilts/jdk/jdk21/linux-x86/bin/java -jar "$apksigner" \
    verify --print-certs "$tmp/$1" | sed -n 's/^Signer #1 certificate SHA-256 digest: //p')
  [ "$cert" = "$MICROG_CERT_SHA256" ] || { echo "not signed by microG: $1 ($cert)"; exit 1; }
}
fetch "$GMS" "$GMS_SHA"
fetch "$STORE" "$STORE_SHA"

rm -rf "$D"; mkdir -p "$D"
mv "$tmp/$GMS" "$D/GmsCore.apk"; mv "$tmp/$STORE" "$D/MicrogCompanion.apk"

# Privileged permissions: every <permission> in the tree whose protectionLevel has "privileged".
rc=0
timeout 600 grep -rl --include=AndroidManifest.xml "<permission" \
  frameworks/base packages/modules packages/services packages/apps packages/providers 2>/dev/null \
  > "$tmp/manifests" || rc=$?
[ "$rc" -le 1 ] || { echo "permission manifest scan failed (rc=$rc)" >&2; exit 1; }
python3 - "$tmp/manifests" "$D" <<'EOF'
import re, subprocess, sys
manifests = [line for line in open(sys.argv[1]).read().splitlines() if line.strip()]
out = sys.argv[2]
priv = set()
for f in manifests:
    try: s = open(f, errors="replace").read()
    except OSError: continue
    for m in re.finditer(r"<permission\b(.*?)/?>", s, re.S):
        a = m.group(1)
        n = re.search(r'android:name="([^"]+)"', a)
        lvl = re.search(r'android:protectionLevel="([^"]+)"', a)
        if n and lvl and "privileged" in lvl.group(1):
            priv.add(n.group(1))
if len(priv) <= 50:
    raise SystemExit(f"too few privileged permissions scanned ({len(priv)}); refusing truncated allowlist")
aapt2 = "prebuilts/sdk/tools/linux/bin/aapt2"
xml = ['<?xml version="1.0" encoding="utf-8"?>',
       "<!-- Generated by scripts/ci/fetch-microg.sh -->", "<permissions>"]
for pkg, apk in (("com.google.android.gms", "GmsCore.apk"),
                 ("com.android.vending", "MicrogCompanion.apk")):
    dump = subprocess.run([aapt2, "dump", "permissions", f"{out}/{apk}"],
                          capture_output=True, text=True, check=True).stdout
    req = sorted(set(re.findall(r"uses-permission(?:-sdk-23)?: name='([^']+)'", dump)) & priv)
    if pkg == "com.google.android.gms" and not req:
        raise SystemExit("com.google.android.gms yielded 0 privileged permissions")
    xml.append(f'    <privapp-permissions package="{pkg}">')
    xml += [f'        <permission name="{p}"/>' for p in req]
    xml.append("    </privapp-permissions>")
    print(pkg, len(req), "privileged permissions")
xml.append("</permissions>")
open(f"{out}/privapp-permissions-microg.xml", "w").write("\n".join(xml) + "\n")
EOF

cat > "$D/default-permissions-microg.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/ci/fetch-microg.sh: what microG's self-check asks for. -->
<exceptions>
    <exception package="com.google.android.gms">
        <permission name="android.permission.ACCESS_FINE_LOCATION" fixed="false"/>
        <permission name="android.permission.ACCESS_COARSE_LOCATION" fixed="false"/>
        <permission name="android.permission.ACCESS_BACKGROUND_LOCATION" fixed="false"/>
        <permission name="android.permission.READ_PHONE_STATE" fixed="false"/>
        <permission name="android.permission.POST_NOTIFICATIONS" fixed="false"/>
    </exception>
    <exception package="com.android.vending">
        <permission name="android.permission.POST_NOTIFICATIONS" fixed="false"/>
    </exception>
</exceptions>
EOF
cat > "$D/microg-sysconfig.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/ci/fetch-microg.sh: push messages must arrive in Doze. -->
<config>
    <allow-in-power-save package="com.google.android.gms"/>
    <allow-in-data-usage-save package="com.google.android.gms"/>
</config>
EOF
cat > "$D/Android.bp" <<'EOF'
// Generated by scripts/ci/fetch-microg.sh (official microG release, signed by microG).
// Its own namespace: only the microg flavour exports it (PRODUCT_SOONG_NAMESPACES in device.mk),
// so it doesn't clash with MindTheGapps' GmsCore in vendor/gapps.
soong_namespace {}

android_app_import {
    name: "GmsCore",
    apk: "GmsCore.apk",
    // Installed byte for byte: by default the build uncompresses a priv-app's dex files, which
    // breaks microG's signature (v2 scheme), and Android then rejects the APK.
    presigned: true,
    preprocessed: true,
    skip_preprocessed_apk_checks: true,
    privileged: true,
    product_specific: true,
    dex_preopt: { enabled: false },
    required: ["privapp-permissions-microg.xml", "default-permissions-microg.xml", "microg-sysconfig.xml"],
}
android_app_import {
    name: "MicrogCompanion",
    apk: "MicrogCompanion.apk",
    // Installed byte for byte: by default the build uncompresses a priv-app's dex files, which
    // breaks microG's signature (v2 scheme), and Android then rejects the APK.
    presigned: true,
    preprocessed: true,
    skip_preprocessed_apk_checks: true,
    privileged: true,
    product_specific: true,
    dex_preopt: { enabled: false },
}
prebuilt_etc {
    name: "privapp-permissions-microg.xml",
    src: "privapp-permissions-microg.xml",
    sub_dir: "permissions",
    product_specific: true,
}
prebuilt_etc {
    name: "default-permissions-microg.xml",
    src: "default-permissions-microg.xml",
    sub_dir: "default-permissions",
    product_specific: true,
}
prebuilt_etc {
    name: "microg-sysconfig.xml",
    src: "microg-sysconfig.xml",
    sub_dir: "sysconfig",
    product_specific: true,
}
EOF
echo "microG $VERSION ready in $D"
