#!/bin/bash
# Install our release keys on the build server as vendor/lineage-priv/keys, so every build (also
# the quick incremental ones) is signed with them instead of AOSP's public test keys.
# The keys live only locally (KEYS_DIR, default ~/.hibreak-release-keys, see docs/signing.md)
# and on the build server's tree; never in git.
#
# What the build does with them (LineageOS 23):
# - keys.mk sets PRODUCT_DEFAULT_DEV_CERTIFICATE to releasekey: apps signed "platform", "shared",
#   ... take the key of that name from this directory, and the build is tagged release-keys.
# - APEX payload keys (<apex>.pem/.avbpubkey) are looked up in the same directory first
#   (build/soong/apex/key.go); a missing one silently falls back to the test key.
# - APEX containers and a few APKs inside APEXes name their certificate through a module, so they
#   get PRODUCT_CERTIFICATE_OVERRIDES to <name>.certificate.override modules defined here.
#
# Usage: CI_HOST=<ip> CI_KEY_DIR=~/.cache/hibreak-ci-key scripts/ci/install-keys.sh
#   (or CI_IDENTITY + CI_KNOWN_HOSTS instead of CI_KEY_DIR; scripts/ci/hcloud-build.sh calls it so
#   with RELEASE_KEYS_DIR set). Needs the synced tree on the server (external/avb).
set -euo pipefail
KEYS_DIR="${KEYS_DIR:-$HOME/.hibreak-release-keys}"
HOST="${CI_HOST:?}"
ID="${CI_IDENTITY:-${CI_KEY_DIR:?set CI_KEY_DIR or CI_IDENTITY}/id_ed25519}"
KH="${CI_KNOWN_HOSTS:-${CI_KEY_DIR:?set CI_KEY_DIR or CI_KNOWN_HOSTS}/known_hosts}"
O=(-i "$ID" -o StrictHostKeyChecking=yes -o "UserKnownHostsFile=$KH" -o GlobalKnownHostsFile=/dev/null -o BatchMode=yes)
DST=/srv/lineage/vendor/lineage-priv/keys
# Staged outside the source tree: a half-written copy with its Android.bp under vendor/ would give
# Soong duplicate modules (keys.tmp next to keys) and break the next build with a confusing error.
STAGE_DIR=/srv/release-keys.stage
[ -f "$KEYS_DIR/releasekey.pk8" ] || { echo "no releasekey.pk8 in $KEYS_DIR" >&2; exit 1; }
[ -f "$KEYS_DIR/avb2048.pem" ] || { echo "no avb2048.pem in $KEYS_DIR" >&2; exit 1; }

# APKs inside APEXes that use explicit certificate overrides instead of releasekey.
APEX_APKS="AdServicesApk HalfSheetUX OsuLogin SafetyCenterResources ServiceConnectivityResources
ServiceUwbResources ServiceWifiResources WifiDialog"

COPYFILE_DISABLE=1 tar --no-xattrs -C "$KEYS_DIR" -cf - . | \
  ssh "${O[@]}" "root@$HOST" "set -euo pipefail; umask 077; rm -rf $STAGE_DIR && mkdir -p $STAGE_DIR && tar -C $STAGE_DIR --no-same-owner -xf -"
ssh "${O[@]}" "root@$HOST" "APEX_APKS='$APEX_APKS' bash -s" <<'EOF'
set -euo pipefail
shopt -s nullglob
umask 077
cd /srv/lineage
DST=vendor/lineage-priv/keys
STAGE=/srv/release-keys.stage
OLD=/srv/release-keys.old
avbtool=external/avb/avbtool.py
bp=$STAGE/Android.bp; mk=$STAGE/keys.mk
[ -f "$STAGE/releasekey.pk8" ] || { echo "staged keys missing releasekey.pk8" >&2; exit 1; }
[ -f "$STAGE/avb2048.pem" ] || { echo "staged keys missing avb2048.pem" >&2; exit 1; }
echo "// Generated by scripts/ci/install-keys.sh" > "$bp"
{
  echo "# Generated by scripts/ci/install-keys.sh"
  echo "PRODUCT_DEFAULT_DEV_CERTIFICATE := vendor/lineage-priv/keys/releasekey"
  echo "PRODUCT_EXTRA_RECOVERY_KEYS :="
  # SELinux recognizes the Bluetooth app by its certificate (keys.conf @BLUETOOTH). AOSP takes it
  # from the test-key directory unless Google's com.google.android.bt is installed, so with our
  # keys the app got no bluetooth domain and crash-looped in zygote (setcontext failed).
  echo "PRODUCT_MAINLINE_BLUETOOTH_SEPOLICY_DEV_CERTIFICATES := vendor/lineage-priv/keys"
} > "$mk"
n=0
for pem in "$STAGE"/com.*.pem; do
  case $pem in *.x509.pem) continue ;; esac
  a=$(basename "$pem" .pem)
  [ -f "$STAGE/$a.pk8" ] || { echo "missing $a.pk8" >&2; exit 1; }
  [ -f "$STAGE/$a.x509.pem" ] || { echo "missing $a.x509.pem" >&2; exit 1; }
  python3 "$avbtool" extract_public_key --key "$pem" --output "$STAGE/$a.avbpubkey"
  # Some apex_key modules name it <apex>.pubkey (com.android.vndk). Without that file the build
  # signs the payload with our key but embeds the test public key, and apexd rejects the APEX at
  # boot (2026-11-16: bootloop at apexd --bootstrap on com.android.vndk.v31).
  cp "$STAGE/$a.avbpubkey" "$STAGE/$a.pubkey"
  printf 'android_app_certificate {\n    name: "%s.certificate.override",\n    certificate: "%s",\n}\n' "$a" "$a" >> "$bp"
  echo "PRODUCT_CERTIFICATE_OVERRIDES += $a:$a.certificate.override" >> "$mk"
  n=$((n + 1))
done
[ "$n" -gt 0 ] || { echo "no APEX keys found in $STAGE" >&2; exit 1; }
printf 'android_app_certificate {\n    name: "hibreak.releasekey.certificate.override",\n    certificate: "releasekey",\n}\n' >> "$bp"
for apk in $APEX_APKS; do echo "PRODUCT_CERTIFICATE_OVERRIDES += $apk:hibreak.releasekey.certificate.override" >> "$mk"; done
printf 'filegroup(\n    name = "android_certificate_directory",\n    srcs = glob([\n        "*.pk8",\n        "*.pem",\n    ]),\n    visibility = ["//visibility:public"],\n)\n' > "$STAGE/BUILD.bazel"
chmod -R go-rwx "$STAGE"
mkdir -p "$(dirname "$DST")"
rm -rf "$OLD"
[ ! -d "$DST" ] || mv "$DST" "$OLD"
mv "$STAGE" "$DST"
rm -rf "$OLD"
echo "installed: $(ls "$DST" | wc -l) files, $n APEX keys"
EOF
